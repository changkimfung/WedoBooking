/**
 * 入库单总箱数模拟：
 * - 字段名 cartons，与「预约送仓-货物明细」cartons 字段保持一致；
 * - 已存在 cartons（>0）的记录不覆盖；
 * - 其余根据 totalQty 派生：cartons = ceil(totalQty / divisor)，
 *   divisor 由 id/orderNo 字符和稳定派生（2~5），保证刷新结果一致且有差异；
 * - totalQty <= 0 或缺失时兜底为 1。
 */
(function ensureInOrderCartons() {
  if (typeof MOCK_IN_ORDER_LIST === 'undefined' || !Array.isArray(MOCK_IN_ORDER_LIST)) return;
  function deriveCartons(item) {
    if (typeof item.cartons === 'number' && item.cartons > 0) return item.cartons;
    var qty = Number(item.totalQty) || 0;
    if (qty <= 0) return 1;
    var key = String(item.id || item.orderNo || '');
    var seed = 0;
    for (var i = 0; i < key.length; i++) seed += key.charCodeAt(i);
    var divisor = 2 + (seed % 4);
    return Math.max(1, Math.ceil(qty / divisor));
  }
  MOCK_IN_ORDER_LIST.forEach(function (item) {
    if (item.cartons === undefined || item.cartons === null || item.cartons === '') {
      item.cartons = deriveCartons(item);
    }
  });
})();

(function normalizeInOrderWarehouseNames() {
  if (typeof normalizeWarehouseName !== 'function') return;
  MOCK_IN_ORDER_LIST.forEach(function (item) {
    if (item.warehouse) item.warehouse = normalizeWarehouseName(item.warehouse);
  });
})();
